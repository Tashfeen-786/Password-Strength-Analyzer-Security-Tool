"""
Terminal/document evidence renders (real captured content only).

Items 01, 02, 22, 23, 24, 25, 28 of the PDF evidence checklist are
documents/terminal output rather than app screens. This script renders the
REAL captured artifacts (project tree, pytest output, schema DDL, live API
response, README) into consistent high-resolution images.

    python scripts/generate_terminal_evidence.py
"""
